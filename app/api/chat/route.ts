// ============================================================
// 文末に改行を入れるユーティリティ（。！？の後に改行）
// ============================================================
function addLineBreaks(text: string): string {
    return text
        // 。！？の後に改行（ただし」』）が続く場合・行末は除く）
        .replace(/([。！？])(?=[^\n」』）\s])/g, "$1\n")
        .trim();
}

